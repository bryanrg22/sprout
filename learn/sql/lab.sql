-- It adds 200,000 made-up exercise rows (the 11 real machines, round-robin), then times two
-- queries with no index, with the index from exercise 11, and with a covering index:
--   the chart:  one machine's whole history (about 18,000 rows, 1 in 11 of the table)
--   the day:    one machine on one day (13 rows)
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 200000),
     machine(k, r) AS (SELECT ZMACHINEKEY, ROW_NUMBER() OVER (ORDER BY Z_PK) - 1 FROM ZEXERCISEENTRY)
INSERT INTO ZEXERCISEENTRY (Z_ENT, Z_OPT, ZREPS, ZSETS, ZDATE, ZWEIGHTLBS, ZMACHINEKEY, ZID, ZSESSIONID)
SELECT 9, 1, 10, 3, 817286400 - i * 600, 50 + (i % 40) * 5, machine.k, randomblob(16), randomblob(16)
FROM n JOIN machine ON machine.r = n.i % 11;

.timer on
.print '-- no index (each query twice: the first run also reads the file from disk)'
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
SELECT COUNT(*) FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' AND ZDATE BETWEEN 817000000 AND 817086400;
SELECT COUNT(*) FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' AND ZDATE BETWEEN 817000000 AND 817086400;
EXPLAIN QUERY PLAN SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE;

.print '-- with the index from exercise 11'
CREATE INDEX exercise_by_machine_date ON ZEXERCISEENTRY (ZMACHINEKEY, ZDATE);
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
SELECT COUNT(*) FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' AND ZDATE BETWEEN 817000000 AND 817086400;
SELECT COUNT(*) FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' AND ZDATE BETWEEN 817000000 AND 817086400;
EXPLAIN QUERY PLAN SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE;

.print '-- with a covering index: the weight is in the index too'
DROP INDEX exercise_by_machine_date;
CREATE INDEX exercise_by_machine_date_weight ON ZEXERCISEENTRY (ZMACHINEKEY, ZDATE, ZWEIGHTLBS);
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
SELECT COUNT(*), MAX(ZWEIGHTLBS) FROM (SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE);
EXPLAIN QUERY PLAN SELECT ZWEIGHTLBS, ZDATE FROM ZEXERCISEENTRY WHERE ZMACHINEKEY = 'leg_press' ORDER BY ZDATE;
