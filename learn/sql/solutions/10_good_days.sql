SELECT date(st.ZDATE + 978307200, 'unixepoch', 'localtime') AS day,
       st.ZCOUNT,
       ROUND(sl.ZASLEEPMINUTES / 60.0, 2) AS hours_asleep
FROM ZSTEPSENTRY AS st
JOIN ZSLEEPENTRY AS sl ON sl.ZDATE = st.ZDATE
WHERE st.ZCOUNT >= (SELECT ZDAILYSTEPGOAL FROM ZUSERPROFILE)
  AND sl.ZASLEEPMINUTES >= 420
ORDER BY st.ZDATE;
